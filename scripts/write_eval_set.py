def main():
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PATH.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDNAMES, quoting=csv.QUOTE_MINIMAL)
        writer.writeheader()
        writer.writerows(ROWS)
    print(f"Wrote {len(ROWS)} rows to {OUT_PATH}")
    # Quick verification
    n_gold = sum(1 for r in ROWS if r["gold_chunks"])
    n_themes = sum(1 for r in ROWS if r["expected_themes"])
    n_refs = sum(1 for r in ROWS if r["reference_answer"])
    print(f"  rows with gold_chunks: {n_gold}")
    print(f"  rows with expected_themes: {n_themes}")
    print(f"  rows with reference_answer: {n_refs}")


if __name__ == "__main__":
    main()